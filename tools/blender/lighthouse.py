# Parola's lighthouse, modelled and rendered to pixel art (see pixelrender.py).
# Run:  blender -b --python tools/blender/lighthouse.py -- <out_dir> [cs_path]
# Heights are screen rows above the ground, matching the old hand-drawn tower (Habagat.cs DrawLighthouse): a stone
# plinth to row 6, the striped tower to row 39 (red and white bands of 11 rows, 5 white), the gallery, the lantern
# from row 41 to 46, the red cap to 50 and a rod above. The lantern glass is "special": the game colours it by the lamp.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bpy
from mathutils import Matrix
from pixelrender import Renderer, args, SPECIAL_KEYS

a = args()
OUT = a[0] if a else "."
CS = a[1] if len(a) > 1 else None
os.makedirs(OUT, exist_ok=True)

TONES = {
    "stone":  ("#6b6f72", "#8a8f93", "#b4b9bc"),
    "white":  ("#c9c3b4", "#ebe7dc", "#faf8f2"),
    "red":    ("#9e3631", "#cf4a3c", "#ec6b55"),
    "iron":   ("#2b2f33", "#43484d", "#666c72"),
    "wood":   ("#3f2818", "#5b3a24", "#7a5230"),
    "window": ("#22262a", "#2f353a", "#3c444a"),
}
# Everything is drawn at SCALE times the old tower's size, which stood about as tall as a tree and looked small.
SCALE = 1.5
S = SCALE
r = Renderer(int(26 * S) + 2, int(64 * S), pitch=30, tones=TONES, special="glass")
M = r.ids

# The plinth: cut stone, faceted so the faces catch the light differently.
PLINTH = 8.2 * S
r.cylinder(0, 0, 0, 6 * S, PLINTH, 7.8 * S, M["stone"], verts=12, smooth=False)
# The tower, a frustum banded red and white from its foot (the band material reads the object's own z, so the mesh is
# moved to start at its origin).
t = r.cylinder(0, 0, 6 * S, 39.5 * S, 6.0 * S, 3.3 * S, None, verts=48)
h = r.Z(33.5 * S)
t.data.transform(Matrix.Translation((0, 0, h / 2)))
t.location.z -= h / 2
t.data.materials.clear()
t.data.materials.append(r.banded("stripes", "Z", r.Z(11 * S), "white", "red", 5 / 11))
# The door at its foot and two small windows up the front.
r.box(0, -5.75 * S, 6 * S, 3.6 * S, 1.0 * S, 5 * S, M["wood"])
r.box(0, -5.75 * S, 10.6 * S, 4.4 * S, 1.0 * S, 0.8 * S, M["stone"])            # a lintel
for z, rad in ((18, 5.05), (29, 4.0)):
    r.box(0, (-rad + 0.2) * S, z * S, 1.6 * S, 1.0 * S, 2.2 * S, M["window"])
# The gallery round the top: an iron ledge with a rail.
r.cylinder(0, 0, 39.8 * S, 40.6 * S, 4.6 * S, 4.6 * S, M["iron"], verts=32)
bpy.ops.mesh.primitive_torus_add(major_radius=4.4 * S, minor_radius=0.3, location=(0, 0, r.Z(42.0 * S)))
bpy.context.object.data.materials.append(M["iron"])
# The lantern: glass with one mullion down the front, like the old drawing.
r.cylinder(0, 0, 40.6 * S, 46 * S, 3.4 * S, 3.4 * S, M["glass"], verts=24)
r.rod((0, -3.45 * S, 40.6 * S), (0, -3.45 * S, 46 * S), 0.45 * S, M["iron"])
# The cap, a finial and the lightning rod.
r.cylinder(0, 0, 46 * S, 46.8 * S, 3.9 * S, 3.9 * S, M["red"], verts=24)
r.cylinder(0, 0, 46.8 * S, 50.2 * S, 3.9 * S, 0.6 * S, M["red"], verts=24)
bpy.ops.mesh.primitive_uv_sphere_add(radius=0.8 * S, location=(0, 0, r.Z(50.6 * S)))
bpy.context.object.data.materials.append(M["iron"])
r.rod((0, 0, 50.6 * S), (0, 0, 53.5 * S), 0.25 * S, M["iron"])

r.aim((0, 0, 27 * S))
# Anchored at the front of the plinth where it meets the ground, so the collision box behind it matches.
ax, ay = r.anchor((0, -PLINTH, 0))
# How far above the anchor the lamp burns, for the beam, and the plinth's half width and depth for the solid box.
lamp = ay - r.anchor((0, 0, 43.3 * S))[1]
footw, footd = int(round(PLINTH)), int(round(2 * PLINTH * math.sin(math.radians(30))))   # the footprint, seen at 30 degrees
grid = r.render(OUT)
UNLIT = ("#56606a", "#6f7b86", "#93a1ac")
r.preview(os.path.join(OUT, "lighthouse-preview.png"), [grid], special_colours=UNLIT)

if CS:
    pal = r.colours([grid])
    lines = [
        "// Generated by tools/blender/lighthouse.py from a 3D model of Parola's lighthouse: don't edit by hand, change",
        "// the model and re-run the script. '.' is clear, letters index Palette, and " + "/".join(SPECIAL_KEYS) + " are the lantern",
        "// glass in shade, base and light, coloured by the game for the lamp. The anchor is the front of the plinth on the ground.",
        "namespace Fesh;",
        "",
        "static class LighthouseArt",
        "{",
        "    public static readonly string[] Palette = { " + ", ".join(f'"{c}"' for c in pal) + " };",
        f"    public const int AnchorX = {ax}, AnchorY = {ay}, LampRise = {lamp}, FootHalfWidth = {footw}, FootDepth = {footd};",
        "    public static readonly string[] Grid =",
        "    {",
    ]
    lines += [f'        "{row}",' for row in r.rows(grid, pal)]
    lines += ["    };", "}"]
    with open(CS, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
print("DONE anchor", ax, ay)
