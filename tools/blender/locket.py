# Mara's locket (the end of the Saltmere mystery), modelled and rendered to pixel art (see pixelrender.py) for the ending card.
# Run:  blender -b --python tools/blender/locket.py -- <out_dir> [cs_path]
# An oval gold locket standing up, faced towards the viewer and seen a little from above: a domed face with a raised rim,
# a little enamel fish on it, the bail at the top and the chain rising from it in a V. Gold gets five tones so it shines.
import os, sys, math
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import bpy
from pixelrender import Renderer, args

a = args()
OUT = a[0] if a else "."
CS = a[1] if len(a) > 1 else None
os.makedirs(OUT, exist_ok=True)

TONES = {
    "gold":   ("#6e4a14", "#a8741f", "#d9a63a", "#f2cf62", "#fff1b0"),
    "rim":    ("#5a3c10", "#8c6018", "#c08a2c", "#e8bc50", "#fbe39a"),
    "enamel": ("#14505a", "#1f7a84", "#3fb0b4"),
    "eye":    ("#1a1a1a", "#2a2a2a", "#3a3a3a"),
}
r = Renderer(44, 64, pitch=12, tones=TONES, lit_at=(0.66, 0.12))
M = r.ids


def obj(mat):
    o = bpy.context.object
    bpy.ops.object.shade_smooth()
    o.data.materials.clear()
    o.data.materials.append(mat)
    return o


# The body: a domed oval lens, 26 x 32, facing the viewer (-y).
CZ = 22          # the middle of the locket, in rows above the anchor
bpy.ops.mesh.primitive_uv_sphere_add(radius=1, segments=48, ring_count=24, location=(0, 0, r.Z(CZ)))
o = obj(M["gold"]); o.scale = (12.5, 5.0, r.Z(15.5))
# The raised rim round its edge.
bpy.ops.mesh.primitive_torus_add(major_radius=1, minor_radius=0.11, major_segments=64, minor_segments=12,
                                 location=(0, -0.6, r.Z(CZ)), rotation=(math.radians(90), 0, 0))
o = obj(M["rim"]); o.scale = (12.6, r.Z(15.6), 12.6)
# A little enamel fish across the middle: body, tail, an eye.
bpy.ops.mesh.primitive_uv_sphere_add(radius=1, segments=24, ring_count=12, location=(1.6, -4.6, r.Z(CZ)))
o = obj(M["enamel"]); o.scale = (5.2, 1.2, r.Z(2.8))
bpy.ops.mesh.primitive_cone_add(vertices=3, radius1=3.4, radius2=0, depth=4, location=(-4.6, -4.3, r.Z(CZ)),
                                rotation=(0, math.radians(90), 0))
o = obj(M["enamel"]); o.scale = (1, 0.5, 1)
bpy.ops.mesh.primitive_uv_sphere_add(radius=0.75, location=(4.8, -5.7, r.Z(CZ + 0.6)))
obj(M["eye"])
# The bail: a ring on top, facing the viewer.
bpy.ops.mesh.primitive_torus_add(major_radius=2.4, minor_radius=0.9, location=(0, -0.5, r.Z(CZ + 17.8)), rotation=(math.radians(90), 0, 0))
obj(M["rim"])
# The chain: oval links up and out to each side, every other one turned.
for side in (-1, 1):
    for i in range(6):
        t = i + 1
        x, z = side * (1.4 + t * 2.3), CZ + 20 + t * 3.4
        rot = (0, math.radians(90), math.radians(side * -34)) if i % 2 == 0 else (math.radians(90), 0, math.radians(side * 56))
        bpy.ops.mesh.primitive_torus_add(major_radius=1.5, minor_radius=0.5, location=(x, 0, r.Z(z)), rotation=rot)
        obj(M["gold"])

r.aim((0, 0, CZ + 9))
ax, ay = r.anchor((0, 0, CZ))      # the anchor is the middle of the locket's face
grid = r.render(OUT)
r.preview(os.path.join(OUT, "locket-preview.png"), [grid])

if CS:
    pal = r.colours([grid])
    lines = [
        "// Generated by tools/blender/locket.py from a 3D model of Mara's locket: don't edit by hand, change the model and",
        "// re-run the script. '.' is clear and letters index Palette. The anchor is the middle of the locket's face.",
        "namespace Fesh;",
        "",
        "static class LocketArt",
        "{",
        "    public static readonly string[] Palette = { " + ", ".join(f'"{c}"' for c in pal) + " };",
        f"    public const int AnchorX = {ax}, AnchorY = {ay};",
        "    public static readonly string[] Grid =",
        "    {",
    ]
    lines += [f'        "{row}",' for row in r.rows(grid, pal)]
    lines += ["    };", "}"]
    with open(CS, "w", encoding="utf8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
print("DONE anchor", ax, ay)
