// Rasterizes the Philippines from Natural Earth's 1:10m land polygons (public domain, naturalearthdata.com) into the
// game's tile grid, true to scale: KM_PER_TILE kilometres a tile, an equirectangular projection squeezed by cos(latitude)
// at the middle of the country. Writes fesh-csharp/src/PhMapData.cs: each row run-length encoded ("12s5l..." = 12 sea,
// 5 land), plus the projection so the game can place real places by latitude and longitude.
// Run:  node tools/phmap/rasterize.js
const fs = require("fs");
const path = require("path");

const KM_PER_TILE = 1.1;
const LON0 = 116.9, LON1 = 126.7, LAT0 = 4.45, LAT1 = 21.2;   // the box: Palawan and Tawi-Tawi to Batanes
const LATC = (LAT0 + LAT1) / 2;
const KX = 111.32 * Math.cos(LATC * Math.PI / 180) / KM_PER_TILE;   // tiles a degree of longitude
const KY = 110.57 / KM_PER_TILE;                                      // tiles a degree of latitude
const COLS = Math.ceil((LON1 - LON0) * KX), ROWS = Math.ceil((LAT1 - LAT0) * KY);

const geo = JSON.parse(fs.readFileSync(path.join(__dirname, "ne_10m_land.geojson"), "utf8"));
const rings = [];
for (const f of geo.features) {
    const g = f.geometry;
    const polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys)
        for (const ring of poly) {
            let inBox = false;
            for (const [lon, lat] of ring) if (lon > LON0 - 1 && lon < LON1 + 1 && lat > LAT0 - 1 && lat < LAT1 + 1) { inBox = true; break; }
            if (inBox) rings.push(ring.map(([lon, lat]) => [(lon - LON0) * KX, (LAT1 - lat) * KY]));
        }
}

// Scanline fill through each tile row's middle (even-odd, so holes such as lakes come out as water).
const grid = Array.from({ length: ROWS }, () => new Uint8Array(COLS));
for (let y = 0; y < ROWS; y++) {
    const cy = y + 0.5, xs = [];
    for (const r of rings)
        for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
            const [x1, y1] = r[i], [x2, y2] = r[j];
            if ((y1 > cy) !== (y2 > cy)) xs.push(x1 + (cy - y1) / (y2 - y1) * (x2 - x1));
        }
    xs.sort((a, b) => a - b);
    for (let k = 0; k + 1 < xs.length; k += 2) {
        const a = Math.max(0, Math.ceil(xs[k] - 0.5)), b = Math.min(COLS - 1, Math.floor(xs[k + 1] - 0.5));
        for (let x = a; x <= b; x++) grid[y][x] ^= 1;
    }
}

// Lakes (Laguna de Bay, Taal) from Natural Earth's 1:10m lakes: land tiles inside them become lake (2, "k" in the rows).
const lakes = JSON.parse(fs.readFileSync(path.join(__dirname, "ne_10m_lakes.geojson"), "utf8"));
const lakeRings = [];
for (const f of lakes.features) {
    const g = f.geometry, polys = g.type === "Polygon" ? [g.coordinates] : g.coordinates;
    for (const poly of polys) {
        const ring = poly[0];
        if (ring.some(([lon, lat]) => lon > LON0 && lon < LON1 && lat > LAT0 && lat < LAT1)) lakeRings.push(ring.map(([lon, lat]) => [(lon - LON0) * KX, (LAT1 - lat) * KY]));
    }
}
for (let y = 0; y < ROWS; y++) {
    const cy = y + 0.5;
    for (const r of lakeRings) {
        const xs = [];
        for (let i = 0, j = r.length - 1; i < r.length; j = i++) {
            const [x1, y1] = r[i], [x2, y2] = r[j];
            if ((y1 > cy) !== (y2 > cy)) xs.push(x1 + (cy - y1) / (y2 - y1) * (x2 - x1));
        }
        xs.sort((a, b) => a - b);
        for (let k = 0; k + 1 < xs.length; k += 2)
            for (let x = Math.max(0, Math.ceil(xs[k] - 0.5)); x <= Math.min(COLS - 1, Math.floor(xs[k + 1] - 0.5)); x++) if (grid[y][x] === 1) grid[y][x] = 2;
    }
}

const rows = grid.map(row => {
    let s = "", run = 0, cur = row[0];
    for (let x = 0; x <= COLS; x++) {
        const v = x < COLS ? row[x] : 255;
        if (v === cur) { run++; continue; }
        s += run + (cur === 1 ? "l" : cur === 2 ? "k" : "s");
        cur = v; run = 1;
    }
    return s;
});
let land = 0, lake = 0; for (const r of grid) for (const v of r) { if (v === 1) land++; if (v === 2) lake++; }

const out = [
    "// Generated by tools/phmap/rasterize.js from Natural Earth's 1:10m land polygons (public domain): don't edit by hand.",
    "// The Philippines, true to scale at KmPerTile kilometres a tile. Each row is run-length encoded: \"12s5l\" is 12 sea",
    "// tiles then 5 land; 'k' marks a lake. Tile (x, y) is at longitude Lon0 + (x + 0.5) / Kx and latitude Lat1 - (y + 0.5) / Ky.",
    "namespace Fesh;",
    "",
    "static class PhMapData",
    "{",
    `    public const int Cols = ${COLS}, Rows = ${ROWS};`,
    `    public const double KmPerTile = ${KM_PER_TILE}, Lon0 = ${LON0}, Lat1 = ${LAT1}, Kx = ${KX.toFixed(6)}, Ky = ${KY.toFixed(6)};`,
    "    public static readonly string[] Land =",
    "    {",
    ...rows.map(r => `        "${r}",`),
    "    };",
    "}",
];
fs.writeFileSync(path.join(__dirname, "..", "..", "fesh-csharp", "src", "PhMapData.cs"), out.join("\n") + "\n");
console.log(`map ${COLS} x ${ROWS} tiles (${(COLS * ROWS / 1e6).toFixed(2)} M), land ${land} tiles, lake ${lake} (${(land / COLS / ROWS * 100).toFixed(1)}%), rings ${rings.length}`);
